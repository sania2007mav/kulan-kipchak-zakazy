def para(text="", bold_prefix=None, style=None):
    p = doc.add_paragraph(style=style)
    if bold_prefix:
        p.add_run(bold_prefix).bold = True
    _rich(p, text)
    return p


def _rich(p, text):
    """**жирный** внутри строки."""
    parts = text.split("**")
    for i, part in enumerate(parts):
        if part:
            p.add_run(part).bold = i % 2 == 1


def bullets(items, style="List Bullet"):
    for item in items:
        _rich(doc.add_paragraph(style=style), item)


def shade(cell, hex_fill):
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hex_fill)
    tc_pr.append(shd)


def table(headers, rows, widths, bold_last=False, align_right=()):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, h in enumerate(headers):
        cell = t.rows[0].cells[i]
        cell.text = ""
        run = cell.paragraphs[0].add_run(h)
        run.bold = True
        run.font.size = Pt(10)
        shade(cell, "E4F0E8")
    for r_idx, row in enumerate(rows):
        cells = t.add_row().cells
        is_total = bold_last and r_idx == len(rows) - 1
        for i, value in enumerate(row):
            cells[i].text = ""
            p = cells[i].paragraphs[0]
            _rich(p, value)
            for run in p.runs:
                run.font.size = Pt(10)
                if is_total:
                    run.bold = True
            if i in align_right:
                p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
            if is_total:
                shade(cells[i], "F3F0E8")
    for row in t.rows:
        for i, w in enumerate(widths):
            row.cells[i].width = Cm(w)
    doc.add_paragraph()
    return t


